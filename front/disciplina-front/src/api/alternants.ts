export interface AlternantEmailCheck {
  exists: boolean
  id: string | null
  fullName: string | null
}

export async function checkAlternantEmail(email: string): Promise<AlternantEmailCheck | null> {
  const trimmed = email.trim()
  if (!trimmed || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(trimmed)) return null
  const res = await pedaGraphqlClient.query(CHECK_ALTERNANT_EMAIL, { email: trimmed }, { requestPolicy: 'network-only' })
  return unwrap<{ alternantByEmail: AlternantEmailCheck }>(res).alternantByEmail
}

