export interface CandidateAutofill {
  candidateId: string
  firstName: string
  lastName: string
  email: string
  phone: string
}

/** Auto-remplissage Identité depuis une fiche candidat (recherche par email). */
export async function lookupCandidateByEmail(email: string): Promise<CandidateAutofill | null> {
  const check = await candidateGraphqlClient.query(CHECK_CANDIDATE_EMAIL, { email }, { requestPolicy: 'network-only' })
  if (check.error) throw new Error(check.error.message.replace(/^\[GraphQL\]\s*/, ''))
  const hit = check.data?.candidateByEmail
  if (!hit?.exists || !hit?.id) return null
  const full = await candidateGraphqlClient.query(GET_CANDIDATE_BY_ID, { id: hit.id }, { requestPolicy: 'network-only' })
  if (full.error) throw new Error(full.error.message.replace(/^\[GraphQL\]\s*/, ''))
  const identity = full.data?.candidate?.identity
  if (!identity) return null
  const parts = String(identity.fullName ?? '').trim().split(/\s+/)
  return {
    candidateId: hit.id,
    firstName: parts[0] ?? '',
    lastName: parts.slice(1).join(' '),
    email: identity.email ?? '',
    phone: identity.phone ?? '',
  }
}
