function unwrap<T>(res: { error?: { message: string }; data?: T }): T {
  if (res.error) throw new Error(res.error.message.replace(/^\[GraphQL\]\s*/, ''))
  return res.data as T
}

export async function fetchAlternants(search?: string): Promise<Alternant[]> {
  const res = await pedaGraphqlClient.query(LIST_ALTERNANTS, { search: search?.trim() || undefined }, { requestPolicy: 'network-only' })
  const data = unwrap<{ alternants: Alternant[] }>(res)
  return data.alternants
}

