export interface AlternantCompany {
  name: string | null
  address: string | null
  mentorName: string | null
  mentorEmail: string | null
  startDate: string | null
  endDate: string | null
}

export interface Alternant {
  id: string
  firstName: string
  lastName: string
  fullName: string
  /** Libellé de la session du jeune (suit le nom de la Session liée). */
  session: string
  /** Session liée (page Sessions) — `null` = libellé libre, hors groupe. */
  sessionId: string | null
  email: string | null
  phone: string | null
  candidateId: string | null
  company: AlternantCompany | null
  linkedAlternantIds: string[]
  /** `true` = archivé suite à une rupture « quitte la formation ». */
  archived: boolean
  archivedAt: string | null
  createdAt: string | null
  updatedAt: string | null
}

export type SequenceStatus = 'pending' | 'done' | 'not_done'

/** Type de séquence (#888/#960) — détermine quel modèle de document s'applique. */
export type AlternantSequenceType = 'j15' | 'j10w' | 'periodique' | 'sa_finale'

export interface SequenceContacts {
  mentor: boolean
  alternant: boolean
  formateur: boolean
}

export interface AlternantSequence {
  id: string
  alternantId: string
  /** Numéro de SA auto-généré. */
  numero: number
  type: AlternantSequenceType
  prevueLe: string
  status: SequenceStatus
  realiseeLe: string | null
  contacts: SequenceContacts
  contactsDone: number
  autoGenerated: boolean
  /** Proposition de RDV envoyée au maître d'apprentissage (#961). */
  appointmentProposedAt: string | null
  /** RDV confirmé par le maître d'apprentissage (lien signé dans le mail). */
  appointmentConfirmedAt: string | null
  /** `true` = archivée avec son alternant (rupture « quitte la formation »). */
  archived: boolean
  archivedAt: string | null
  createdAt: string | null
  updatedAt: string | null
}

export interface CreateAlternantInput {
  firstName: string
  lastName: string
  session: string
  sessionId?: string | null
  email?: string | null
  phone?: string | null
  candidateId?: string | null
  company: {
    name?: string | null
    address?: string | null
    mentorName?: string | null
    mentorEmail?: string | null
    startDate: string
    endDate?: string | null
  }
  linkedAlternantIds?: string[]
}
