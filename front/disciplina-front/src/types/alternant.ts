export interface AlternantCompany {
  name: string | null
  address: string | null
  mentorName: string | null
  startDate: string | null
  endDate: string | null
}

export interface Alternant {
  id: string
  firstName: string
  lastName: string
  fullName: string
  /** Libellé de la session du jeune (suit le nom de la Session liée). */
  session: string
  /** Session liée (page Sessions) — `null` = libellé libre, hors groupe. */
  sessionId: string | null
  email: string | null
  phone: string | null
  candidateId: string | null
  /** Financeur de la formation (OPCO, Région…) — affiché sur l'émargement. */
  financeur: string | null
  company: AlternantCompany | null
  linkedAlternantIds: string[]
  /** `true` = folder Filiz encore à son étape de départ (dossier pas fini de remplir). */
  filizInProgress: boolean
  /** `true` = archivé suite à une rupture « quitte la formation ». */
  archived: boolean
  archivedAt: string | null
  /** Raison de l'archivage — `null` si actif. */
  archiveReason: AlternantArchiveReason | null
  createdAt: string | null
  updatedAt: string | null
}

export type SequenceStatus = 'pending' | 'done' | 'not_done'

export interface SequenceContacts {
  mentor: boolean
  alternant: boolean
  formateur: boolean
}

export interface AlternantSequence {
  id: string
  alternantId: string
  /** Numéro de SA auto-généré. */
  numero: number
  prevueLe: string
  status: SequenceStatus
  realiseeLe: string | null
  contacts: SequenceContacts
  contactsDone: number
  autoGenerated: boolean
  /** `true` = archivée avec son alternant (rupture « quitte la formation »). */
  archived: boolean
  archivedAt: string | null
  createdAt: string | null
  updatedAt: string | null
}

export interface CreateAlternantInput {
  firstName: string
  lastName: string
  session: string
  sessionId?: string | null
  email?: string | null
  phone?: string | null
  candidateId?: string | null
  financeur?: string | null
  company: {
    name?: string | null
    address?: string | null
    mentorName?: string | null
    startDate: string
    endDate?: string | null
  }
  linkedAlternantIds?: string[]
}
