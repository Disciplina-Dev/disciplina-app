import gql from 'graphql-tag';

export const typeDefs = gql`
    enum AlternantSequenceStatus {
        pending
        done
        not_done
    }

    enum AlternantArchiveReason {
        rupture
        fin_formation
    }

    type AlternantCompany {
        name: String
        address: String
        mentorName: String
        siret: String
        opco: String
        contactEmail: String
        contactPhone: String
        startDate: String
        endDate: String
    }

    type CandidateEmployer {
        name: String
        siret: String
        opco: String
        address: String
        mentorName: String
        contactName: String
        contactEmail: String
        contactPhone: String
        startDate: String
        sessionId: String
    }

    type Alternant {
        id: ID!
        firstName: String!
        lastName: String!
        fullName: String!
        session: String!
        sessionId: String
        email: String
        phone: String
        candidateId: String
        company: AlternantCompany
        linkedAlternantIds: [String!]!
        filizInProgress: Boolean!
        archived: Boolean!
        archivedAt: String
        archiveReason: AlternantArchiveReason
        createdAt: String
        updatedAt: String
    }

    type SessionPerson {
        firstName: String!
        lastName: String!
        mailAddress: String!
    }

    type SessionDegree {
        id: ID!
        title: String!
    }

    type SessionSyncResult {
        degrees: Int!
        classes: Int!
    }

    input SessionPersonInput {
        firstName: String!
        lastName: String!
        mailAddress: String!
    }

    input SessionAddressInput {
        street: String
        complement: String
        city: String
        postcode: String
        country: String
    }

    input CreateSessionInput {
        degreeId: ID!
        nom: String!
        dateDebut: String!
        dateFin: String!
        subjectValidation: Boolean!
        generalEducationDuration: String
        headTeacher: SessionPersonInput
        referentTeacher: SessionPersonInput
        realizationAddress: SessionAddressInput
    }

    type SessionAddress {
        housenumber: String!
        street: String!
        complement: String!
        city: String!
        postcode: String!
        country: String!
        formatted: String!
    }

    type Session {
        id: ID!
        nom: String!
        filiere: String
        jourCours: String
        dateDebut: String!
        dateFin: String!
        headTeacher: SessionPerson
        referentTeacher: SessionPerson
        realizationAddress: SessionAddress
        alternantCount: Int!
        createdAt: String
        updatedAt: String
    }

    type AlternantSequenceContacts {
        mentor: Boolean!
        alternant: Boolean!
        formateur: Boolean!
    }

    type AlternantSequence {
        id: ID!
        alternantId: ID!
        numero: Int!
        prevueLe: String!
        status: AlternantSequenceStatus!
        realiseeLe: String
        contacts: AlternantSequenceContacts!
        contactsDone: Int!
        autoGenerated: Boolean!
        archived: Boolean!
        archivedAt: String
        createdAt: String
        updatedAt: String
    }

    input AlternantCompanyInput {
        name: String
        address: String
        mentorName: String
        siret: String
        opco: String
        contactEmail: String
        contactPhone: String
        startDate: String!
        endDate: String
    }

    input CreateAlternantInput {
        firstName: String!
        lastName: String!
        session: String!
        sessionId: String
        email: String
        phone: String
        candidateId: String
        company: AlternantCompanyInput!
        linkedAlternantIds: [String!]
    }

    input UpdateAlternantInput {
        firstName: String
        lastName: String
        session: String
        sessionId: String
        email: String
        phone: String
        candidateId: String
    }

    input AlternantSequenceContactsInput {
        mentor: Boolean
        alternant: Boolean
        formateur: Boolean
    }

    type AlternantEmailCheck {
        exists: Boolean!
        id: String
        fullName: String
    }

    type Rupture {
        id: ID!
        alternantId: ID!
        firstName: String
        lastName: String
        fullName: String!
        session: String!
        sessionId: String
        dateRupture: String!
        entreprise: String
        motif: String!
        detail: String
        poursuitFormation: Boolean!
        createdAt: String
        updatedAt: String
    }

    input DeclareRuptureInput {
        alternantId: ID!
        dateRupture: String!
        entreprise: String
        motif: String!
        detail: String
        poursuitFormation: Boolean!
    }

    input UpdateRuptureInput {
        dateRupture: String
        entreprise: String
        motif: String
        detail: String
        poursuitFormation: Boolean
    }

    type Query {
        alternants(search: String, includeArchived: Boolean): [Alternant!]!
        alternant(id: ID!): Alternant
        alternantSequences(alternantId: ID!): [AlternantSequence!]!
        alternantByEmail(email: String!): AlternantEmailCheck!
        candidateEmployer(candidateId: ID!): CandidateEmployer
        sessions(search: String): [Session!]!
        session(id: ID!): Session
        sessionDegrees: [SessionDegree!]!
        sessionAlternants(sessionId: ID!): [Alternant!]!
        ruptures(year: Int!, month: Int!): [Rupture!]!
        alternantRuptures(alternantId: ID!): [Rupture!]!
    }

    type Mutation {
        createAlternant(input: CreateAlternantInput!): Alternant!
        updateAlternant(id: ID!, input: UpdateAlternantInput!): Alternant
        deleteAlternant(id: ID!): Boolean!
        changeAlternantCompany(id: ID!, company: AlternantCompanyInput!): Alternant
        removeAlternantCompany(id: ID!): Alternant
        linkAlternant(id: ID!, otherId: ID!): Alternant
        unlinkAlternant(id: ID!, otherId: ID!): Alternant
        archiveAlternant(id: ID!, reason: AlternantArchiveReason = rupture): Alternant
        unarchiveAlternant(id: ID!): Alternant
        createSequence(alternantId: ID!, prevueLe: String!): AlternantSequence!
        rescheduleSequence(id: ID!, prevueLe: String!): AlternantSequence
        updateSequenceContacts(id: ID!, contacts: AlternantSequenceContactsInput!): AlternantSequence
        completeSequence(id: ID!, realiseeLe: String!): AlternantSequence
        markSequence(id: ID!, status: AlternantSequenceStatus!): AlternantSequence
        deleteSequence(id: ID!): Boolean!
        declareRupture(input: DeclareRuptureInput!): Rupture!
        updateRupture(id: ID!, input: UpdateRuptureInput!): Rupture
        deleteRupture(id: ID!): Boolean!
        renameSession(id: ID!, nom: String!): Session
        createSession(input: CreateSessionInput!): Session!
        syncSessionReference: SessionSyncResult!
    }
`;
