import gql from 'graphql-tag';

export const typeDefs = gql`
    enum AlternantSequenceStatus {
        pending
        done
        not_done
    }

    enum AlternantSequenceType {
        j15
        j10w
        periodique
        sa_finale
    }

    type AlternantCompany {
        name: String
        address: String
        mentorName: String
        startDate: String
        endDate: String
    }

    type Alternant {
        id: ID!
        firstName: String!
        lastName: String!
        fullName: String!
        session: String!
        sessionId: String
        email: String
        phone: String
        candidateId: String
        company: AlternantCompany
        linkedAlternantIds: [String!]!
        archived: Boolean!
        archivedAt: String
        createdAt: String
        updatedAt: String
    }

    type Session {
        id: ID!
        nom: String!
        filiere: String
        jourCours: String
        documentTemplateId: String
        dateDebut: String!
        dateFin: String!
        alternantCount: Int!
        createdAt: String
        updatedAt: String
    }

    type AlternantSequenceContacts {
        mentor: Boolean!
        alternant: Boolean!
        formateur: Boolean!
    }

    type AlternantSequence {
        id: ID!
        alternantId: ID!
        numero: Int!
        type: AlternantSequenceType!
        prevueLe: String!
        status: AlternantSequenceStatus!
        realiseeLe: String
        contacts: AlternantSequenceContacts!
        contactsDone: Int!
        autoGenerated: Boolean!
        archived: Boolean!
        archivedAt: String
        createdAt: String
        updatedAt: String
    }

    input AlternantCompanyInput {
        name: String
        address: String
        mentorName: String
        startDate: String!
        endDate: String
    }

    input CreateAlternantInput {
        firstName: String!
        lastName: String!
        session: String!
        sessionId: String
        email: String
        phone: String
        candidateId: String
        company: AlternantCompanyInput!
        linkedAlternantIds: [String!]
    }

    input UpdateAlternantInput {
        firstName: String
        lastName: String
        session: String
        sessionId: String
        email: String
        phone: String
        candidateId: String
    }

    input CreateSessionInput {
        nom: String!
        filiere: String
        jourCours: String
        documentTemplateId: String
        dateDebut: String!
        dateFin: String!
    }

    input UpdateSessionInput {
        nom: String
        filiere: String
        jourCours: String
        documentTemplateId: String
        dateDebut: String
        dateFin: String
    }

    input AlternantSequenceContactsInput {
        mentor: Boolean
        alternant: Boolean
        formateur: Boolean
    }

    "Modèle de document pour une SA (#888). j15/j10w : 2 lignes système permanentes. periodique : créables/supprimables, choisies par Session."
    type AlternantDocumentTemplate {
        id: ID!
        type: AlternantSequenceType!
        label: String!
        maitreApprentissage: String!
        alternant: String!
        formateur: String!
        createdAt: String
        updatedAt: String
    }

    input AlternantDocumentTemplateInput {
        label: String!
        maitreApprentissage: String!
        alternant: String!
        formateur: String!
    }

    type AlternantSequenceDocumentHeader {
        alternantFullName: String!
        session: String
        companyName: String
        mentorName: String
        companyStartDate: String
        companyEndDate: String
    }

    "Les 3 parties d'un document (texte riche), sans en-tête ni signatures — contenu brut d'un modèle."
    type AlternantSequenceDocumentParts {
        maitreApprentissage: String
        alternant: String
        formateur: String
    }

    "Document résolu d'une SA : le contenu déjà sauvegardé (isSnapshotted=true), ou sinon le modèle applicable comme point de départ."
    type AlternantSequenceDocument {
        sequenceId: ID!
        header: AlternantSequenceDocumentHeader!
        maitreApprentissage: String
        alternant: String
        formateur: String
        "Signature dessinée par partie (PNG en data-URL) — usage informel, aucune valeur légale."
        signatureMaitreApprentissage: String
        signatureAlternant: String
        signatureFormateur: String
        isSnapshotted: Boolean!
        "Contenu brut du modèle résolu, indépendant du snapshot déjà sauvegardé — pour le bouton Réinitialiser au modèle vierge."
        template: AlternantSequenceDocumentParts
    }

    input SaveAlternantSequenceDocumentInput {
        maitreApprentissage: String!
        alternant: String!
        formateur: String!
        signatureMaitreApprentissage: String
        signatureAlternant: String
        signatureFormateur: String
    }

    type AlternantEmailCheck {
        exists: Boolean!
        id: String
        fullName: String
    }

    type Rupture {
        id: ID!
        alternantId: ID!
        firstName: String
        lastName: String
        fullName: String!
        session: String!
        sessionId: String
        dateRupture: String!
        entreprise: String
        motif: String!
        detail: String
        poursuitFormation: Boolean!
        createdAt: String
        updatedAt: String
    }

    input DeclareRuptureInput {
        alternantId: ID!
        dateRupture: String!
        entreprise: String
        motif: String!
        detail: String
        poursuitFormation: Boolean!
    }

    input UpdateRuptureInput {
        dateRupture: String
        entreprise: String
        motif: String
        detail: String
        poursuitFormation: Boolean
    }

    type Query {
        alternants(search: String, includeArchived: Boolean): [Alternant!]!
        alternant(id: ID!): Alternant
        alternantSequences(alternantId: ID!): [AlternantSequence!]!
        alternantByEmail(email: String!): AlternantEmailCheck!
        sessions(search: String): [Session!]!
        session(id: ID!): Session
        sessionAlternants(sessionId: ID!): [Alternant!]!
        ruptures(year: Int!, month: Int!): [Rupture!]!
        alternantRuptures(alternantId: ID!): [Rupture!]!
        alternantDocumentTemplates(type: AlternantSequenceType): [AlternantDocumentTemplate!]!
        alternantSequenceDocument(sequenceId: ID!): AlternantSequenceDocument!
    }

    type Mutation {
        createAlternant(input: CreateAlternantInput!): Alternant!
        updateAlternant(id: ID!, input: UpdateAlternantInput!): Alternant
        deleteAlternant(id: ID!): Boolean!
        changeAlternantCompany(id: ID!, company: AlternantCompanyInput!): Alternant
        removeAlternantCompany(id: ID!): Alternant
        linkAlternant(id: ID!, otherId: ID!): Alternant
        unlinkAlternant(id: ID!, otherId: ID!): Alternant
        archiveAlternant(id: ID!): Alternant
        unarchiveAlternant(id: ID!): Alternant
        createSequence(alternantId: ID!, prevueLe: String!, type: AlternantSequenceType): AlternantSequence!
        rescheduleSequence(id: ID!, prevueLe: String!): AlternantSequence
        updateSequenceContacts(id: ID!, contacts: AlternantSequenceContactsInput!): AlternantSequence
        completeSequence(id: ID!, realiseeLe: String!): AlternantSequence
        markSequence(id: ID!, status: AlternantSequenceStatus!): AlternantSequence
        deleteSequence(id: ID!): Boolean!
        createSession(input: CreateSessionInput!): Session!
        updateSession(id: ID!, input: UpdateSessionInput!): Session
        deleteSession(id: ID!): Boolean!
        assignAlternantToSession(sessionId: ID!, alternantId: ID!): Session
        removeAlternantFromSession(sessionId: ID!, alternantId: ID!): Session
        declareRupture(input: DeclareRuptureInput!): Rupture!
        updateRupture(id: ID!, input: UpdateRuptureInput!): Rupture
        deleteRupture(id: ID!): Boolean!
        createAlternantDocumentTemplate(input: AlternantDocumentTemplateInput!): AlternantDocumentTemplate!
        updateAlternantDocumentTemplate(id: ID!, input: AlternantDocumentTemplateInput!): AlternantDocumentTemplate!
        deleteAlternantDocumentTemplate(id: ID!): Boolean!
        saveAlternantSequenceDocument(
            sequenceId: ID!
            input: SaveAlternantSequenceDocumentInput!
        ): AlternantSequenceDocument!
    }
`;
